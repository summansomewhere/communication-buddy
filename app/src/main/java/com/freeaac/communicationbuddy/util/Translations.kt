    /**
     * Translate an English word to the target language. Currently supports "Spanish" / "es".
     * If no translation is found or the language is English, returns the original word.
     */
    fun translate(word: String, language: String): String {
        return when (language.lowercase()) {
            "spanish", "es" -> EN_TO_ES[word.lowercase()] ?: word
            else -> word // Default English
        }
    }

    fun translateCategory(category: String, language: String): String {
        return when (language.lowercase()) {
            "spanish", "es" -> CATEGORY_EN_TO_ES[category] ?: category
            else -> category
        }
    }

    fun translateUI(text: String, language: String): String {
        return when (language.lowercase()) {
            "spanish", "es" -> UI_EN_TO_ES[text] ?: text
            else -> text
        }
    }
